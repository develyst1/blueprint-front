// Writes src/core/theme/registry.generated.ts from the theme folders (SPEC-B-001 R8: a theme is found by its
// folder, not by a core edit). A folder is a theme once it has src/themes/<id>/index.ts or index.tsx exporting
// `theme: Theme`; a folder without one (a theme still being built) is skipped, so it never breaks the build.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const themesDir = path.join(root, "src/themes");
const out = path.join(root, "src/core/theme/registry.generated.ts");

const ids = existsSync(themesDir)
  ? readdirSync(themesDir, { withFileTypes: true })
      .filter((d) => d.isDirectory() && /^[a-z0-9-]+$/.test(d.name))
      .filter((d) => ["index.ts", "index.tsx"].some((f) => existsSync(path.join(themesDir, d.name, f))))
      .map((d) => d.name)
      .sort()
  : [];

const lines = [
  "// GENERATED by scripts/gen-theme-registry.mjs — do not edit, do not commit (git-ignored).",
  'import type { Theme } from "./contract";',
  ...ids.map((id, i) => `import { theme as t${i} } from "@/themes/${id}";`),
  "",
  "export const themes: Record<string, Theme> = {",
  ...ids.map((id, i) => `  ${JSON.stringify(id)}: t${i},`),
  "};",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`themes: ${ids.length ? ids.join(", ") : "none"}`);
